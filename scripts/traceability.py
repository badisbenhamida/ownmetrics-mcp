"""Requirement -> test traceability (AC2).

Reads requirement IDs from SPEC.md tables, finds tests tagged `@pytest.mark.req(...)`,
writes TRACEABILITY.md, and with --check fails when an in-scope automated requirement has
no test, or a test cites an ID that SPEC.md does not define.

Usage: python scripts/traceability.py [--milestone M2] [--check]
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPEC = ROOT / "SPEC.md"
TESTS = ROOT / "tests"
OUT = ROOT / "TRACEABILITY.md"
ID_RE = re.compile(r"^(T|I|R|AC|C|L)\d+$")


@dataclass
class Requirement:
    rid: str
    text: str
    milestone: str | None
    verify: str | None
    tests: list[str] = field(default_factory=list)


def parse_spec(path: Path = SPEC) -> dict[str, Requirement]:
    reqs: dict[str, Requirement] = {}
    header: list[str] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|"):
            header = []
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if set("".join(cells)) <= set("- :"):
            continue
        if not header:
            header = [c.lower() for c in cells]
            continue
        if not ID_RE.match(cells[0]):
            continue
        row = dict(zip(header, cells, strict=False))
        text = (
            row.get("requirement")
            or row.get("criterion")
            or row.get("rule")
            or row.get("limitation")
            or cells[-1]
        )
        tool = row.get("tool")
        reqs[cells[0]] = Requirement(
            cells[0],
            f"{tool}: {text}" if tool else text,
            row.get("milestone"),
            row.get("verify"),
        )
    return reqs


def _req_ids(decorator: ast.expr) -> list[str]:
    if not isinstance(decorator, ast.Call):
        return []
    fn = decorator.func
    name = fn.attr if isinstance(fn, ast.Attribute) else getattr(fn, "id", "")
    if name != "req":
        return []
    return [
        a.value for a in decorator.args if isinstance(a, ast.Constant) and isinstance(a.value, str)
    ]


def collect_tests(tests_dir: Path = TESTS) -> dict[str, list[str]]:
    found: dict[str, list[str]] = {}
    for path in sorted(tests_dir.glob("test_*.py")):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef) and node.name.startswith(
                "test"
            ):
                for dec in node.decorator_list:
                    for rid in _req_ids(dec):
                        found.setdefault(rid, []).append(f"{path.name}::{node.name}")
    return found


def milestone_num(m: str | None) -> int:
    return int(m[1:]) if m and m[:1] == "M" and m[1:].isdigit() else 99


def render(reqs: dict[str, Requirement], milestone: str) -> str:
    lines = [
        "# Traceability matrix",
        "",
        "Generated by `scripts/traceability.py` from SPEC.md and the tests "
        f"(scope: up to {milestone}).",
        "Do not edit by hand.",
        "",
        "| ID | Requirement | Milestone | Verify | Tests |",
        "| --- | --- | --- | --- | --- |",
    ]
    order = {"C": 0, "T": 1, "I": 2, "R": 3, "AC": 4, "L": 5}

    def key(r: Requirement) -> tuple[int, int]:
        prefix = re.match(r"[A-Z]+", r.rid).group(0)  # type: ignore[union-attr]
        return order.get(prefix, 9), int(r.rid[len(prefix) :])

    for r in sorted(reqs.values(), key=key):
        tests = "<br>".join(f"`{t}`" for t in r.tests) or (
            "manual check at gate"
            if r.verify == "manual"
            else "—"
            if milestone_num(r.milestone) > milestone_num(milestone)
            else "**MISSING**"
        )
        text = r.text.replace("|", "\\|")
        lines.append(f"| {r.rid} | {text} | {r.milestone or '—'} | {r.verify or '—'} | {tests} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--milestone", default="M2")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args(argv)

    reqs = parse_spec()
    tests = collect_tests()
    unknown = sorted(set(tests) - set(reqs))
    for rid, names in tests.items():
        if rid in reqs:
            reqs[rid].tests = names

    OUT.write_text(render(reqs, args.milestone), encoding="utf-8")
    scope = milestone_num(args.milestone)
    missing = [
        r.rid
        for r in reqs.values()
        if r.verify == "auto" and milestone_num(r.milestone) <= scope and not r.tests
    ]
    print(
        f"{len(reqs)} requirements, {sum(len(v) for v in tests.values())} test links; "
        f"wrote {OUT.name}"
    )
    if unknown:
        print("Tests cite IDs not defined in SPEC.md:", ", ".join(unknown))
    if missing:
        print(
            f"In-scope ({args.milestone}) automated requirements with no test:", ", ".join(missing)
        )
    if args.check and (unknown or missing):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
